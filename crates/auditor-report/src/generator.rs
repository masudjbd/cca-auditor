pub async fn generate(
    db: Arc<DbPool>,
    session_ids: Vec<Uuid>,
    format: ReportFormat,
) -> Result<Vec<u8>> {
    // Fetch all sessions, then filter to requested IDs
    let all_sessions = get_sessions(&db, 1000)?;
    let filtered_sessions: Vec<_> = if session_ids.is_empty() {
        all_sessions
    } else {
        all_sessions
            .into_iter()
            .filter(|s| session_ids.contains(&s.id))
            .collect()
    };

    // Fetch events for each session
    let mut all_events = Vec::new();
    for session in &filtered_sessions {
        let evs = get_events(&db, session.id, 5000)?;
        all_events.extend(evs);
    }

    // Compute stats
    let unique_tools: std::collections::HashSet<_> =
        filtered_sessions.iter().map(|s| s.tool_id.0.clone()).collect();
    let high_confidence = filtered_sessions
        .iter()
        .filter(|s| matches!(s.confidence, auditor_core::tool::Confidence::High))
        .count();

    let now = chrono::Local::now().format("%Y-%m-%d %H:%M:%S %Z").to_string();

    // Format sessions for template
    let sessions_view: Vec<_> = filtered_sessions
        .iter()
        .map(|s| {
            json!({
                "tool_id": s.tool_id.0,
                "pid": s.pid,
                "started_at": s.started_at.to_string(),
                "confidence": format!("{:?}", s.confidence),
            })
        })
        .collect();

    // Format events for template
    let events_view: Vec<_> = all_events
        .iter()
        .map(|e| {
            let (kind, detail) = match &e.kind {
                auditor_core::events::EventKind::FsRead { path } => ("fs_read", path.clone()),
                auditor_core::events::EventKind::FsWrite { path } => ("fs_write", path.clone()),
                auditor_core::events::EventKind::FsDelete { path } => ("fs_delete", path.clone()),
                auditor_core::events::EventKind::NetConnect { addr, port, .. } => {
                    ("net_connect", format!("{}:{}", addr, port))
                }
                auditor_core::events::EventKind::ProcessSpawn { exe, .. } => {
                    ("process_spawn", exe.clone())
                }
                auditor_core::events::EventKind::LocalArtifact { path, .. } => {
                    ("local_artifact", path.clone())
                }
            };
            json!({
                "timestamp": e.timestamp.to_string(),
                "kind": kind,
                "detail": detail,
                "confidence": format!("{:?}", e.confidence),
            })
        })
        .collect();

    // Build context
    let mut ctx = Context::new();
    ctx.insert("generated_at", &now);
    ctx.insert("session_count", &filtered_sessions.len());
    ctx.insert("event_count", &all_events.len());
    ctx.insert("unique_tools", &unique_tools.len());
    ctx.insert("high_confidence", &high_confidence);
    ctx.insert("sessions", &sessions_view);
    ctx.insert("events", &events_view);

    match format {
        ReportFormat::Json => {
            let report = json!({
                "generated_at": now,
                "session_count": filtered_sessions.len(),
                "event_count": all_events.len(),
                "unique_tools": unique_tools.len(),
                "high_confidence": high_confidence,
                "sessions": sessions_view,
                "events": events_view,
            });
            Ok(serde_json::to_vec_pretty(&report)?)
        }
        ReportFormat::Html => {
            let mut tera = Tera::default();
            tera.add_raw_template("report.html", HTML_TEMPLATE)?;
            let rendered = tera.render("report.html", &ctx)?;
            Ok(rendered.into_bytes())
        }
        ReportFormat::Markdown => {
            let mut tera = Tera::default();
            tera.add_raw_template("report.md", MARKDOWN_TEMPLATE)?;
            let rendered = tera.render("report.md", &ctx)?;
            Ok(rendered.into_bytes())
        }
        ReportFormat::Pdf => {
            // For now, render HTML and document that PDF requires external conversion
            let mut tera = Tera::default();
            tera.add_raw_template("report.html", HTML_TEMPLATE)?;
            let rendered = tera.render("report.html", &ctx)?;
            // Note: a full PDF implementation would use printpdf or headless Chrome
            // For now, return HTML with instruction
            Ok(rendered.into_bytes())
        }
    }
}
