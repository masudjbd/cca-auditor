#[derive(Debug, Clone, Copy)]
pub enum ReportFormat {
    Html,
    Pdf,
    Markdown,
    Json,
}

impl ReportFormat {
    pub fn from_str(s: &str) -> Option<Self> {
        match s {
            "html" => Some(ReportFormat::Html),
            "pdf" => Some(ReportFormat::Pdf),
            "markdown" | "md" => Some(ReportFormat::Markdown),
            "json" => Some(ReportFormat::Json),
            _ => None,
        }
    }
}

